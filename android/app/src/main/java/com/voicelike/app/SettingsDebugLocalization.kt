internal fun buildIndexDebugDeviceSummary(
    context: android.content.Context,
    copy: SettingsDebugCopy
): String {
    val resolvedModel = DeviceModelNameResolver.resolveCameraLabel(context, Build.MODEL)
    return buildString {
        append(copy.deviceInfo)
        append('\n')
        append(copy.appBuild).append(": ").append(AppRuntimeLogStore.buildSummary(context))
        append('\n')
        append(copy.brand).append(": ").append(Build.BRAND)
        append('\n')
        append(copy.manufacturer).append(": ").append(Build.MANUFACTURER)
        append('\n')
        append(copy.model).append(": ").append(resolvedModel)
        append('\n')
        append(copy.modelCode).append(": ").append(Build.MODEL)
        append('\n')
        append(copy.device).append(": ").append(Build.DEVICE)
        append('\n')
        append(copy.product).append(": ").append(Build.PRODUCT)
        append('\n')
        append(copy.android).append(": ")
            .append(Build.VERSION.RELEASE ?: "unknown")
            .append(" (SDK ")
            .append(Build.VERSION.SDK_INT)
            .append(")")
        append('\n')
        append(copy.buildId).append(": ").append(Build.ID)
        append('\n')
        append(copy.display).append(": ").append(Build.DISPLAY)
    }
}

internal fun buildIndexDebugCopyText(
    context: android.content.Context,
    runtimeLogs: List<RuntimeLogEntry>,
    copy: SettingsDebugCopy
): String {
    val logText = runtimeLogs.joinToString("\n") { it.formatLine() }
    return buildString {
        append(buildIndexDebugDeviceSummary(context, copy))
        append('\n')
        append('\n')
        append(copy.runtimeLogsLast24h)
        append('\n')
        append(logText.ifBlank { copy.noLogsLast24h })
    }
}
