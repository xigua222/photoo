    private fun resolveColorCardFilterFeedSectionKey(
        candidate: ColorCardTraceFilterCandidate
    ): String {
        if (candidate.kind == ColorCardTraceFilterKind.AiMnn) return "AI"
        if (candidate.kind == ColorCardTraceFilterKind.MotionPhotoEntry) return "creative_visual"
        return when (candidate.title.trim().lastOrNull()?.uppercaseChar()) {
            'P', 'V' -> "creative_visual"
            'J', 'A' -> "A"
            'M', 'F' -> "F"
            'C' -> "C"
            else -> {
                val paletteId = candidate.paletteId.removePrefix("builtin_hald:")
                when {
                    paletteId.startsWith("black-white") -> "A"
                    paletteId.startsWith("cinematic") ||
                        paletteId.startsWith("fg-cine") ||
                        paletteId.startsWith("cinema") ||
                        paletteId.contains("bleach") ||
                        paletteId.contains("resolve") ||
                        paletteId.contains("501") ||
                        paletteId.contains("5219") ||
                        paletteId.contains("ektraglide") -> "C"
                    paletteId.startsWith("film-sim-") ||
                        paletteId.startsWith("polaroid-") ||
                        paletteId.startsWith("classic-neg") ||
                        paletteId.startsWith("nostalgic-neg") ||
                        paletteId.startsWith("eterna") ||
                        paletteId.startsWith("pro-neg") ||
                        paletteId.startsWith("fuj-07-velvia") ||
                        paletteId.startsWith("fuj-") ||
                        paletteId.startsWith("astia") ||
                        paletteId.startsWith("reala-") ||
                        paletteId.startsWith("velvia") ||
                        paletteId.startsWith("provia") ||
                        paletteId.startsWith("print-film") ||
                        paletteId.startsWith("film-boost") ||
                        paletteId.startsWith("film-tone") -> "F"
                    paletteId.startsWith("classic-memory-") ||
                        paletteId.startsWith("j-fresh-") -> "F"
                    else -> "Style"
                }
            }
        }
    }
