internal fun OrganizeResultStrings.kindTitle(kind: String): String = when (kind) {
    OrganizeKind.PHOTO -> kindPhoto
    OrganizeKind.LIVE -> kindLive
    OrganizeKind.VIDEO -> kindVideo
    OrganizeKind.SCREENSHOT -> kindScreenshot
    OrganizeKind.SCREEN_RECORDING -> kindScreenRecording
    OrganizeKind.PANORAMA -> kindPanorama
    OrganizeKind.ANIMATED -> kindAnimated
    OrganizeKind.RAW -> kindRaw
    else -> allPhotos
}

