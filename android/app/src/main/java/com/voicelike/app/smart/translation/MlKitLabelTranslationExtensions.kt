    fun merge(base: Map<String, Map<String, String>>): Map<String, Map<String, String>> {
        val merged = LinkedHashMap<String, Map<String, String>>(base.size + directMap.size)
        base.forEach { (key, translations) ->
            merged[key.trim().lowercase()] = translations
        }
        // Overlay, not replace: the asset also carries languages this table does not list.
        directMap.forEach { (key, translations) ->
            merged[key] = (merged[key] ?: emptyMap()) + translations
        }
        return merged
    }

