/** Long date: "2014年3月2日" / "March 2, 2014". */
internal fun InsightStrings.fullDate(dayValue: Int): String = formatDay(fullDatePattern, dayValue)

internal fun InsightStrings.fullDate(dayKey: String): String =
    InsightStatsEngine.parseDayKey(dayKey)?.let { fullDate(it) } ?: dayKey

private fun InsightStrings.formatDay(pattern: String, dayValue: Int): String {
    val calendar = GregorianCalendar(locale)
    calendar.clear()
    calendar.set(dayValue / 10000, (dayValue / 100) % 100 - 1, dayValue % 100, 12, 0, 0)
    val formatter = SimpleDateFormat(pattern, locale)
    formatter.calendar = calendar
    return formatter.format(calendar.time)
}

/** "%d 年前" / "%d yr ago". */
internal fun InsightStrings.yearsAgo(years: Int): String = format(insYearsAgoFmt, years)

/** Full weekday names, index 0 = Sunday ("星期日", "Sunday", "dimanche"). */
internal fun InsightStrings.weekdayNames(): List<String> {
    val names = DateFormatSymbols.getInstance(locale).weekdays
    return (Calendar.SUNDAY..Calendar.SATURDAY).map { names[it] }
}

/** Abbreviated weekday names, index 0 = Sunday ("周日", "Sun"). */
internal fun InsightStrings.shortWeekdayNames(): List<String> {
    val names = DateFormatSymbols.getInstance(locale).shortWeekdays
    return (Calendar.SUNDAY..Calendar.SATURDAY).map { names[it].trimEnd('.') }
}

/** One-glyph weekday names for chart axes, index 0 = Sunday ("日", "S", "CN"). */
