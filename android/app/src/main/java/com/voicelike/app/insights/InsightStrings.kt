/**
 * Drill page title (without the count). Scoped drills join the period title and the group name;
 * Day / Month use their own date label. [cameraName] prettifies raw camera labels
 * (pass DeviceModelNameResolver.resolveCameraLabel on Android).
 */
internal fun InsightStrings.drillTitle(
    drill: InsightDrill,
    period: InsightPeriod,
    cameraName: (String) -> String = ::insightCameraDisplayName
): String {
    val periodTitle = periodTitle(period)
    fun scoped(name: String) = insightTitleJoin(periodTitle, name)
    return when (drill) {
        InsightDrill.Period -> periodTitle
        InsightDrill.Photos -> scoped(photos)
        InsightDrill.Videos -> scoped(videos)
        InsightDrill.Screenshots -> scoped(screenshots)
        InsightDrill.Located -> scoped(locationLabel)
        InsightDrill.Liked -> scoped(liked)
        is InsightDrill.Day -> dayLabel(drill.dayKey)
        is InsightDrill.Month -> monthLabel(drill.monthKey)
        is InsightDrill.Camera -> scoped(cameraName(drill.raw))
        is InsightDrill.Place -> scoped(drill.label)
        is InsightDrill.Keyword -> scoped(insightKeywordDisplayName(drill.word))
        is InsightDrill.Weekday -> scoped(weekdayNames().getOrElse(drill.weekday - 1) { drill.weekday.toString() })
        is InsightDrill.Daypart -> scoped(insightDaypartTitle(drill.part))
        is InsightDrill.Format -> scoped(formatTitle(drill.format))
        is InsightDrill.Orientation -> scoped(orientationTitle(drill.orientation))
        is InsightDrill.Shooting -> scoped(drill.param.rangeLabel(drill.binIndex))
    }
}
