    AppLanguage.SimplifiedChinese, AppLanguage.TraditionalChinese, AppLanguage.Japanese, AppLanguage.Korean ->
        shortWeekdayNames().map { if (it.isEmpty()) it else it.takeLast(1) }
    AppLanguage.Vietnamese -> listOf("CN", "T2", "T3", "T4", "T5", "T6", "T7")
    AppLanguage.Thai -> listOf("อา", "จ", "อ", "พ", "พฤ", "ศ", "ส")
