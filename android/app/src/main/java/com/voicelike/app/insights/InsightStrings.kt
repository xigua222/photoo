// MARK: Numbers

/** Grouped integer: "52,318". */
internal fun InsightStrings.number(value: Long): String = NumberFormat.getIntegerInstance(locale).format(value)

internal fun InsightStrings.number(value: Int): String = number(value.toLong())

/** Whole percentage: "72%". */
internal fun InsightStrings.percent(fraction: Double): String {
    val formatter = NumberFormat.getPercentInstance(locale)
    formatter.maximumFractionDigits = 0
    formatter.roundingMode = RoundingMode.HALF_UP
    return formatter.format(fraction)
}

/** Signed whole percentage: "+18%", "-12%". */
internal fun InsightStrings.signedPercent(fraction: Double): String {
    val body = percent(abs(fraction))
    return when {
        fraction > 0 -> "+$body"
        fraction < 0 -> "-$body"
        else -> body
    }
}

/** "8,213 km" / "8,213 公里". */
internal fun InsightStrings.distance(kilometers: Double): String =
    format(distanceFmt, number(kilometers.roundToLong()))

/** "1 小时 20 分" / "1 hr 20 min"; rounds to whole minutes. */
internal fun InsightStrings.duration(seconds: Double): String {
    val minutes = (maxOf(seconds, 0.0) / 60).roundToLong()
    val hours = minutes / 60
    val rest = minutes % 60
    return when {
        hours > 0 && rest > 0 -> format(durationHMFmt, number(hours), number(rest))
        hours > 0 -> format(durationHFmt, number(hours))
        else -> format(durationMFmt, number(rest))
    }
}

/** Multiplier text: ≥ 10 whole, else one decimal ("2.5"). */
internal fun InsightStrings.ratio(value: Double): String =
    if (value >= 10) number(value.roundToLong()) else String.format(locale, "%.1f", value)

