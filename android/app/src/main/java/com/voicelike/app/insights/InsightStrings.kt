// MARK: Text joining

/** "天空、夜空和户外" / "sky, night sky, and outdoor". */
internal fun InsightStrings.listJoin(items: List<String>): String = when (items.size) {
    0 -> ""
    1 -> items[0]
    2 -> items[0] + listPairSeparator + items[1]
    else -> items.dropLast(1).joinToString(listSeparator) + listFinalSeparator + items.last()
}

private fun isHanOrKana(c: Char): Boolean {
    val v = c.code
    return v in 0x3040..0x30FF || v in 0x3400..0x4DBF || v in 0x4E00..0x9FFF || v in 0xF900..0xFAFF || v in 0xFF66..0xFF9F
}

/** Lead + name ("2026年" + "相机" -> "2026年相机", "2026" + "Cameras" -> "2026 Cameras"). */
internal fun insightTitleJoin(lead: String, name: String): String {
    if (lead.isEmpty()) return name
    if (name.isEmpty()) return lead
    return if (isHanOrKana(lead.last()) && isHanOrKana(name.first())) lead + name else "$lead $name"
}

