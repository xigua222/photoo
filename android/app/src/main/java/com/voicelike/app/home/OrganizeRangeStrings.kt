// --- Dates -------------------------------------------------------------------
// Numbers are always written with Western digits; only month names are localized.

private enum class OrganizeDateStyle { Chinese, Korean, MonthFirst, DayFirstSlash, DayFirstDot }

private fun organizeDateStyle(language: AppLanguage): OrganizeDateStyle = when (language) {
    AppLanguage.SimplifiedChinese, AppLanguage.TraditionalChinese, AppLanguage.Japanese -> OrganizeDateStyle.Chinese
    AppLanguage.Korean -> OrganizeDateStyle.Korean
    AppLanguage.English -> OrganizeDateStyle.MonthFirst
    AppLanguage.German, AppLanguage.Russian, AppLanguage.Ukrainian, AppLanguage.Polish, AppLanguage.Czech,
    AppLanguage.Finnish, AppLanguage.Norwegian, AppLanguage.Danish, AppLanguage.Turkish, AppLanguage.Romanian,
    AppLanguage.Hebrew -> OrganizeDateStyle.DayFirstDot
    else -> OrganizeDateStyle.DayFirstSlash
}

internal fun organizeRangeLocale(language: AppLanguage): Locale = when (language) {
    AppLanguage.SimplifiedChinese -> Locale.SIMPLIFIED_CHINESE
    AppLanguage.TraditionalChinese -> Locale.TRADITIONAL_CHINESE
    else -> Locale.forLanguageTag(language.code)
}

private fun organizeMonthName(month: Int, language: AppLanguage): String {
    val locale = organizeRangeLocale(language)
    val calendar = Calendar.getInstance(locale).apply {
        clear()
        set(2000, (month - 1).coerceIn(0, 11), 1)
    }
    return runCatching { SimpleDateFormat("LLL", locale).format(calendar.time) }
        .getOrNull()
        ?.takeIf { it.isNotBlank() }
        ?: month.toString()
}

/** Month card title in the month list: "3月" / "3월" / "Mar". */
internal fun organizeMonthCardLabel(month: Int, language: AppLanguage): String = when (organizeDateStyle(language)) {
    OrganizeDateStyle.Chinese -> "${month}月"
    OrganizeDateStyle.Korean -> "${month}월"
    else -> organizeMonthName(month, language)
}

/** "yyyy-MM" to "2026年3月" / "2026년 3월" / "Mar 2026". */
internal fun organizeMonthLabel(monthKey: String, language: AppLanguage): String {
    val year = monthKey.take(4).toIntOrNull()
    val month = monthKey.drop(5).take(2).toIntOrNull()
    if (year == null || month == null || month !in 1..12) return monthKey
    return when (organizeDateStyle(language)) {
        OrganizeDateStyle.Chinese -> "${year}年${month}月"
        OrganizeDateStyle.Korean -> "${year}년 ${month}월"
        else -> "${organizeMonthName(month, language)} $year"
    }
}

/** "yyyy-MM-dd" to a short ("3月5日") or full ("2026年3月5日") date. */
internal fun organizeDayLabel(dayKey: String, language: AppLanguage, withYear: Boolean): String {
    val parts = dayKey.split("-")
    if (parts.size != 3) return dayKey
    val year = parts[0].toIntOrNull() ?: return dayKey
    val month = parts[1].toIntOrNull() ?: return dayKey
    val day = parts[2].toIntOrNull() ?: return dayKey
    return when (organizeDateStyle(language)) {
        OrganizeDateStyle.Chinese -> if (withYear) "${year}年${month}月${day}日" else "${month}月${day}日"
        OrganizeDateStyle.Korean -> if (withYear) "${year}년 ${month}월 ${day}일" else "${month}월 ${day}일"
        OrganizeDateStyle.MonthFirst -> if (withYear) "$month/$day/$year" else "$month/$day"
        OrganizeDateStyle.DayFirstSlash -> if (withYear) "$day/$month/$year" else "$day/$month"
        OrganizeDateStyle.DayFirstDot -> if (withYear) "$day.$month.$year" else "$day.$month."
    }
}

// --- Range titles ------------------------------------------------------------

internal fun organizeKindTitle(kind: String, language: AppLanguage): String {
    val strings = organizeRangeStrings(language)
    return when (kind) {
        OrganizeKind.PHOTO -> strings.kindPhoto
        OrganizeKind.LIVE -> strings.kindLive
        OrganizeKind.VIDEO -> strings.kindVideo
        OrganizeKind.SCREENSHOT -> strings.kindScreenshot
        OrganizeKind.SCREEN_RECORDING -> strings.kindScreenRecording
        OrganizeKind.PANORAMA -> strings.kindPanorama
        OrganizeKind.ANIMATED -> strings.kindAnimated
        OrganizeKind.RAW -> strings.kindRaw
        else -> strings.all
    }
}

/** Album name as shown in the panel; a blank bucket name reads as "Uncategorized". */
internal fun organizeAlbumTitle(name: String, language: AppLanguage): String = when {
    name == "All" -> organizeRangeStrings(language).all
    name.isBlank() -> organizeRangeStrings(language).uncategorized
    else -> name
}

/**
 * Time part of a range, or null when time is "All". [short] drops the year from
 * picked / random days (panel pills); titles keep it.
 */
internal fun organizeTimeTitle(criteria: MediaFilterCriteria, language: AppLanguage, short: Boolean = false): String? {
    val strings = organizeRangeStrings(language)
    return when (criteria.timePreset) {
        OrganizeTimePreset.TODAY -> strings.today
        OrganizeTimePreset.ON_THIS_DAY -> strings.onThisDay
        OrganizeTimePreset.RANDOM_DAY ->
            if (criteria.day != "All") organizeDayLabel(criteria.day, language, withYear = !short) else strings.randomDay
        else -> when {
            criteria.day != "All" -> organizeDayLabel(criteria.day, language, withYear = !short)
            criteria.month != "All" -> organizeMonthLabel(criteria.month, language)
            else -> null
        }
    }
}

/** Non-"All" parts joined with " | " in the order time, album, kind; "All Photos" when nothing is set. */
internal fun organizeRangeTitle(criteria: MediaFilterCriteria, language: AppLanguage): String {
    criteria.collectionTitle?.takeIf { criteria.isCollection }?.let { return it }
    val parts = buildList {
        organizeTimeTitle(criteria, language)?.let(::add)
        if (criteria.folder != "All") add(organizeAlbumTitle(criteria.folder, language))
        if (criteria.type != "All") add(organizeKindTitle(criteria.type, language))
    }
    return if (parts.isEmpty()) organizeRangeStrings(language).allPhotos else parts.joinToString(" | ")
}
