// and ar are translated here. Formats take %d (counts) or %s (album name).
internal data class OrganizeRangeStrings(
    val title: String,
    val reset: String,
    val sectionTime: String,
    val sectionAlbum: String,
    val sectionType: String,
    val all: String,
    val today: String,
    val onThisDay: String,
    val randomDay: String,
    val pickDate: String,
    val kindPhoto: String,
    val kindLive: String,
    val kindVideo: String,
    val kindScreenshot: String,
    val kindScreenRecording: String,
    val kindPanorama: String,
    val kindAnimated: String,
    val kindRaw: String,
    val hideAlbum: String,
    val pinAlbum: String,
    val unpinAlbum: String,
    val hiddenAlbums: String,
    val noHiddenAlbums: String,
    val unhideTitle: String,
    val unhideMessageFormat: String,
    val confirm: String,
    val cancel: String,
    val organizeFormat: String,
    val nothingToOrganize: String,
    val albumDone: String,
    val photosCountFormat: String,
    val wholeMonth: String,
    val busiestDays: String,
    val allPhotos: String,
    val uncategorized: String
) {
    fun organizeLabel(count: Int): String = organizeFormat.replace("%d", count.toString())
    fun photosCount(count: Int): String = photosCountFormat.replace("%d", count.toString())
    fun unhideMessage(name: String): String = unhideMessageFormat.replace("%s", name)
}

